def create_app(config: Optional[AppConfig] = None, *, stack: Optional[Stack] = None):
    """Build the FastAPI application.

    ``stack`` lets tests inject a pre-built (small-corpus) stack; otherwise it is
    built from ``config`` at creation time. Raises a clear ImportError with an
    install hint if FastAPI isn't available.
    """
    try:
        from fastapi import FastAPI
        from fastapi.responses import HTMLResponse, JSONResponse
    except ImportError as exc:  # pragma: no cover - exercised only without the extra
        raise ImportError(_FASTAPI_HINT) from exc

    stack = stack or build_stack(config)

    app = FastAPI(
        title="Shia-Aalim",
        description="Evidence-first Twelver Shia research & lecture assistant. "
        "No citation = not a fact.",
        version="0.1.0",
    )
    app.state.stack = stack

    @app.get("/", response_class=HTMLResponse)
    async def index() -> str:
        return INDEX_HTML

    @app.get("/api/status")
    async def status() -> dict:
        cfg = stack.config
        return {
            "documents": stack.n_documents,
            "embedders": [
                {"spec": spec, "state": stack.embedder_state(spec),
                 "default": spec == stack.default_embedder}
                for spec in stack.embedders
            ],
            "default_embedder": stack.default_embedder,
            "synthesizer": cfg.synthesize,
            "judge": cfg.judge,
            "decomposer": cfg.decompose,
            "default_k": cfg.default_k,
        }

    @app.get("/api/sources")
    async def sources() -> dict:
        return stack.facets()

    @app.post("/api/answer")
    async def api_answer(body: AskBody):
        question = (body.question or "").strip()
        if not question:
            return JSONResponse({"error": "question is required"}, status_code=400)
        try:
            engine = stack.engine(body.embedder)
        except EmbedderUnavailable as exc:
            return JSONResponse({"error": _embedder_error(body.embedder, exc)}, status_code=503)
        k = _clamp_int(body.k, default=stack.config.default_k, lo=1, hi=25)
        answer = engine.answers.answer(
            question,
            k=k,
            evidence_types=_parse_types(body.evidence_types),
            source_ids=_parse_sources(body.source_ids),
            min_confidence=_parse_confidence(body.min_confidence),
        )
        markdown = engine.answers.format_markdown(answer)
        payload = answer_to_payload(answer, markdown)
        payload["embedder"] = body.embedder or stack.default_embedder
        return payload

    @app.post("/api/lecture")
    async def api_lecture(body: LectureBody):
        topic = (body.topic or "").strip()
        if not topic:
            return JSONResponse({"error": "topic is required"}, status_code=400)
        try:
            engine = stack.engine(body.embedder)
        except EmbedderUnavailable as exc:
            return JSONResponse({"error": _embedder_error(body.embedder, exc)}, status_code=503)
        depth = _clamp_int(body.depth, default=4, lo=1, hi=10)
        lecture = engine.lectures.generate(
            topic, depth=depth, source_ids=_parse_sources(body.source_ids)
        )
        payload = lecture_to_payload(lecture)
        payload["embedder"] = body.embedder or stack.default_embedder
        return payload

    @app.post("/api/compare")
    async def api_compare(body: CompareBody):
        question = (body.question or "").strip()
        if not question:
            return JSONResponse({"error": "question is required"}, status_code=400)
        sources = [s for s in (body.sources or []) if s]
        if not sources:
            return JSONResponse({"error": "select at least one book to compare"}, status_code=400)
        try:
            engine = stack.engine(body.embedder)
        except EmbedderUnavailable as exc:
            return JSONResponse({"error": _embedder_error(body.embedder, exc)}, status_code=503)

        truncated = len(sources) > MAX_COMPARE_SOURCES
        sources = sources[:MAX_COMPARE_SOURCES]
        k = _clamp_int(body.k, default=4, lo=1, hi=15)
        types = _parse_types(body.evidence_types)
        conf = _parse_confidence(body.min_confidence)
        titles = {s["id"]: s["title"] for s in stack.facets()["sources"]}

        columns = []
        for sid in sources:
            # Same question, each book answered on its own evidence only.
            ans = engine.answers.answer(
                question, k=k, evidence_types=types, source_ids={sid}, min_confidence=conf
            )
            columns.append({
                "source_id": sid,
                "title": titles.get(sid, sid),
                "answer": ans.to_dict(),
                "markdown": engine.answers.format_markdown(ans),
            })
        return {
            "question": question,
            "embedder": body.embedder or stack.default_embedder,
            "columns": columns,
            "truncated": truncated,
        }

    return app


def _parse_types(values: Optional[list[str]]) -> Optional[list[EvidenceType]]:
    """Turn incoming strings into EvidenceType values; unknown ones are dropped."""
    if not values:
        return None
    out: list[EvidenceType] = []
    for v in values:
        try:
            out.append(EvidenceType(v))
        except ValueError:
            continue
    return out or None


def _parse_sources(values: Optional[list[str]]) -> Optional[set[str]]:
    if not values:
        return None
    picked = {v for v in values if v}
    return picked or None


def _parse_confidence(value: Optional[str]) -> ConfidenceLevel:
    """Map a floor string to a ConfidenceLevel; default LOW (the generator default)."""
    if not value:
        return ConfidenceLevel.LOW
    try:
        return ConfidenceLevel(value)
    except ValueError:
        return ConfidenceLevel.LOW


def _embedder_error(spec: Optional[str], exc: Exception) -> str:
    return (
        f"The '{spec}' embedder is not available in this environment: {exc}. "
        "Semantic models (st:…) need the [embeddings] extra and a reachable "
        "model; switch back to the tfidf index."
    )


def _clamp_int(value, *, default: int, lo: int, hi: int) -> int:
    try:
        n = int(value)
    except (TypeError, ValueError):
        return default
    return max(lo, min(hi, n))


