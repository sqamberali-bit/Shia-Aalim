# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Serve the Shia-Aalim web front-end (FastAPI + uvicorn).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    # Defaults come from the environment first so a container/PaaS can configure
    # the server without changing the command (HOST/PORT/KNOWLEDGE_DIR/EMBEDDER).
    parser.add_argument("--host", default=os.environ.get("HOST", "127.0.0.1"))
    parser.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8000")))
    parser.add_argument("--knowledge-dir",
                        default=os.environ.get("KNOWLEDGE_DIR", str(DEFAULT_KNOWLEDGE_DIR)))
    parser.add_argument("--registry", default=str(DEFAULT_REGISTRY))
    parser.add_argument(
        "--embedder", default=os.environ.get("EMBEDDER", "tfidf"),
        help="one or a comma-separated list to offer as a UI toggle; the first is "
        "the default (e.g. 'tfidf' or 'tfidf,st:BAAI/bge-m3'). tfidf | hashing | st:<model>",
    )
    parser.add_argument("--synthesize", default=os.environ.get("SYNTHESIZE", "none"),
                        help="none | mock | claude:<model> (env: SYNTHESIZE; needs ANTHROPIC_API_KEY)")
    parser.add_argument("--judge", default=os.environ.get("JUDGE", "lexical"),
                        help="lexical | mock | claude:<model> (env: JUDGE)")
    parser.add_argument("--decompose", default=os.environ.get("DECOMPOSE", "none"),
                        help="none | rule | claude:<model> (env: DECOMPOSE)")
    parser.add_argument("--refine", default=os.environ.get("REFINE", "none"),
                        help="AI query correction: none | mock | claude:<model> (env: REFINE)")
    parser.add_argument("--k", type=int, default=int(os.environ.get("K", "8")),
                        help="default evidence passages per answer (env: K)")
    args = parser.parse_args(argv)

    try:
        import uvicorn
    except ImportError:
        print(_FASTAPI_HINT, file=sys.stderr)
        return 1

    embedders = [s.strip() for s in args.embedder.split(",") if s.strip()] or ["tfidf"]
    cache_env = os.environ.get("INDEX_CACHE_DIR")
    config = AppConfig(
        knowledge_dir=Path(args.knowledge_dir),
        registry_path=Path(args.registry),
        embedders=embedders,
        synthesize=args.synthesize,
        judge=args.judge,
        decompose=args.decompose,
        refine=args.refine,
        default_k=args.k,
        cache_dir=Path(cache_env) if cache_env else None,
    )
    print(f"Loading corpus from {config.knowledge_dir} …", file=sys.stderr)
    app = create_app(config)
    n = app.state.stack.n_documents
    extra = [e for e in embedders[1:]]
    switch = f" (+{', '.join(extra)} on first use)" if extra else ""
    print(
        f"Loaded {n:,} documents; default index '{config.default_embedder}' ready{switch}. "
        f"Serving Shia-Aalim on http://{args.host}:{args.port}",
        file=sys.stderr,
    )
    uvicorn.run(app, host=args.host, port=args.port)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
