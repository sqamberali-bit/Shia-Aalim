# The compare view runs one retrieval per selected book; cap the fan-out.
MAX_COMPARE_SOURCES = 6


class EmbedderUnavailable(RuntimeError):
    """A configured embedder could not be built (e.g. semantic model unreachable)."""


@dataclass
class AppConfig:
    """How to build the retrieval + generation stack behind the web app."""

    knowledge_dir: Path = DEFAULT_KNOWLEDGE_DIR
    registry_path: Path = DEFAULT_REGISTRY
    embedders: list[str] = field(default_factory=lambda: ["tfidf"])
    synthesize: str = "none"
    judge: str = "lexical"
    decompose: str = "none"
    refine: str = "none"
    default_k: int = 6
    # When set, each embedder's vectors are cached here (embed once, reuse across
    # restarts). Essential for semantic embedders — the corpus is embedded at
    # build time (scripts/warm_index.py) and loaded instantly at runtime.
    cache_dir: Optional[Path] = None

    @property
    def default_embedder(self) -> str:
        return self.embedders[0]


@dataclass
class Engine:
    """The two generators bound to one embedder's index."""

    answers: AnswerGenerator
    lectures: LectureGenerator


class Stack:
    """Holds the corpus and builds a per-embedder :class:`Engine` on demand.

    Each embedder needs its *own* index (the vectors differ), so switching
    embedders means querying a different retriever. Indexes are built lazily and
    cached: the default embedder is built eagerly (validating the corpus at
    startup); any additional configured embedder is built the first time it is
    requested, and a build failure (e.g. an unreachable semantic model) is cached
    and surfaced as :class:`EmbedderUnavailable` rather than retried or crashed.
    """

    def __init__(
        self,
        docs: list[Document],
        config: AppConfig,
        known: Optional[set[str]] = None,
        sources_meta: Optional[dict[str, Source]] = None,
    ) -> None:
        self.docs = docs
        self.config = config
        self.known = known
        self.sources_meta = sources_meta or {}
        self.provider_notes: list[str] = []
        # Providers are index-independent, so build them once and share. LLM-backed
        # ones are guarded: a missing/invalid API key must NOT crash the server —
        # it degrades to extractive answers with a note.
        self._synthesizer = self._safe("synthesizer", make_synthesizer, config.synthesize)
        self._judge = self._safe("judge", make_judge, config.judge) or make_judge("lexical")
        self._decomposer = self._safe("decomposer", make_decomposer, config.decompose)
        self._refiner = self._safe("refiner", make_refiner, config.refine)
        # The judge that VERIFIES synthesised prose (semantic entailment, incl.
        # cross-lingual). This is what stops genuine AI synthesis from being
        # wrongly rejected by lexical word-overlap. Prefer an explicit claude
        # JUDGE; otherwise, when Claude synthesis is on, auto-build a FAST Haiku
        # verifier (cheaper/quicker than re-using the synthesis model).
        self._cross_lingual_judge = None
        if config.judge.startswith("claude"):
            self._cross_lingual_judge = self._judge  # explicit claude judge doubles as verifier
        elif config.synthesize.startswith("claude"):
            self._cross_lingual_judge = self._safe(
                "verifier", make_judge, "claude:claude-haiku-4-5-20251001")
        self._engines: dict[str, Engine] = {}
        self._errors: dict[str, str] = {}
        self._facets: Optional[dict] = None
        self._verse_index: Optional[dict] = None
        self._narrators: Optional[NarratorIndex] = None

    def _safe(self, label: str, factory, spec):
        """Build an optional (often LLM-backed) provider without crashing on error."""
        try:
            return factory(spec)
        except Exception as exc:  # noqa: BLE001 - a bad key/spec must not down the server
            if spec and spec != "none":
                self.provider_notes.append(f"{label} '{spec}' unavailable: {exc}")
            return None

    @property
    def n_documents(self) -> int:
        return len(self.docs)

    def verse_index(self) -> dict:
        """``(surah, ayah) -> verse Document`` for cross-referencing, built once."""
        if self._verse_index is None:
            self._verse_index = build_verse_index(self.docs)
        return self._verse_index

    def narrators(self) -> NarratorIndex:
        """The rijāl / narrator index (chain reading + grade attributions), built once."""
        if self._narrators is None:
            self._narrators = NarratorIndex(self.docs)
        return self._narrators

    def crossref(self, engine: "Engine") -> CrossReferencer:
        """A CrossReferencer bound to a built engine's retriever."""
        return CrossReferencer(engine.answers.retriever, self.verse_index())

    def facets(self) -> dict:
        """What's actually in this corpus: source books and evidence types.

        Powers the UI filter panel. Computed once from the loaded documents
        (joined with registry titles/confidence) and cached.
        """
        if self._facets is not None:
            return self._facets
        from collections import Counter

        src_count: Counter = Counter()
        type_count: Counter = Counter()
        src_types: dict[str, set[str]] = {}
        for d in self.docs:
            sid = d.citation.source_id
            src_count[sid] += 1
            type_count[d.evidence_type.value] += 1
            src_types.setdefault(sid, set()).add(d.evidence_type.value)

        sources = []
        for sid, n in src_count.most_common():
            meta = self.sources_meta.get(sid)
            sources.append({
                "id": sid,
                "title": meta.title if meta else sid,
                "confidence": meta.confidence.value if meta else None,
                "count": n,
                "evidence_types": sorted(src_types.get(sid, ())),
            })
        self._facets = {
            "sources": sources,
            "evidence_types": [{"type": t, "count": n} for t, n in type_count.most_common()],
        }
        return self._facets

    @property
    def embedders(self) -> list[str]:
        return list(self.config.embedders)

    @property
    def default_embedder(self) -> str:
        return self.config.default_embedder

    def embedder_state(self, spec: str) -> str:
        """``ready`` (built), ``failed`` (build errored), or ``lazy`` (not yet built)."""
        if spec in self._engines:
            return "ready"
        if spec in self._errors:
            return "failed"
        return "lazy"

    def error_for(self, spec: str) -> Optional[str]:
        return self._errors.get(spec)

    def engine(self, spec: Optional[str] = None) -> Engine:
        """Return the Engine for ``spec`` (default embedder if None), building it once."""
        spec = spec or self.default_embedder
        if spec not in self.config.embedders:
            raise EmbedderUnavailable(
                f"Embedder {spec!r} is not enabled. Available: "
                + ", ".join(self.config.embedders)
            )
        if spec in self._engines:
            return self._engines[spec]
        if spec in self._errors:
            raise EmbedderUnavailable(self._errors[spec])
        try:
            retriever = self._build_retriever(spec)
        except Exception as exc:  # noqa: BLE001 - report, don't crash the server
            self._errors[spec] = str(exc)
            raise EmbedderUnavailable(str(exc)) from exc
        # A semantic (sentence-transformers) index can bridge scripts; a lexical
        # one cannot. This gates the honest cross-lingual caveat on answers.
        multilingual = spec.startswith(("st:", "sentence-transformers:"))
        engine = Engine(
            answers=AnswerGenerator(
                retriever,
                synthesizer=self._synthesizer,
                known_source_ids=self.known,
                judge=self._judge,
                decomposer=self._decomposer,
                multilingual=multilingual,
                refiner=self._refiner,
                cross_lingual_judge=self._cross_lingual_judge,
            ),
            lectures=LectureGenerator(
                retriever, synthesizer=self._synthesizer, judge=self._judge
            ),
        )
        self._engines[spec] = engine
        return engine

    def _build_retriever(self, spec: str) -> Retriever:
        """Build (or load from the on-disk cache) the retriever for one embedder.

        With ``cache_dir`` set, vectors are cached per embedder — so a semantic
        index embedded once at build time loads instantly at runtime instead of
        re-embedding the whole corpus on every start.
        """
        embedder = make_embedder(spec)
        if self.config.cache_dir is None:
            return build_index(self.docs, embedder=embedder)
        safe = spec.replace("/", "_").replace(":", "_")
        cache_path = Path(self.config.cache_dir) / f"{safe}.pkl"
        store = build_persistent_index(self.docs, embedder, cache_path)
        return Retriever(store)


def build_stack(config: Optional[AppConfig] = None) -> Stack:
    """Load the corpus and prepare the generators (default index built eagerly).

    Pure pipeline code — no web dependency — so it is unit-testable on its own
    and reused by both the API and any embedded use.
    """
    config = config or AppConfig()
    docs = list(iter_knowledge_dir(config.knowledge_dir))
    if not docs:
        raise RuntimeError(
            f"No documents found under {config.knowledge_dir}. Build the corpus "
            "first (python scripts/ingest.py) or point --knowledge-dir at a "
            "directory of .jsonl knowledge files."
        )
    known = _load_known_ids(config.registry_path)
    sources_meta = _load_sources_meta(config.registry_path)
    stack = Stack(docs, config, known, sources_meta)
    stack.engine(config.default_embedder)  # eager: validate corpus + default index
    return stack


def _load_known_ids(registry_path: Path) -> Optional[set[str]]:
    try:
        return load_registry_ids(registry_path)
    except FileNotFoundError:
        return None


def _load_sources_meta(registry_path: Path) -> dict[str, Source]:
    try:
        return {s.id: s for s in load_sources(registry_path)}
    except FileNotFoundError:
        return {}


