"""Local web front-end for Shia-Aalim (FastAPI).

This wraps the *same* :class:`~shia_aalim.generation.answer.AnswerGenerator` and
:class:`~shia_aalim.generation.lecture.LectureGenerator` that ``scripts/demo.py``
uses in a tiny HTTP API plus a single self-contained HTML page, so the assistant
can be used in a browser instead of the terminal.

Nothing here weakens the charter guarantees. The web layer only *presents* what
the pipeline produces: answers are generated by the exact same grounded
retrieval + verification path, every claim still carries its citation and
confidence, and the grounding firewall still withholds anything it can't verify.
The browser just renders that structured output.

    pip install -e ".[web]"          # fastapi + uvicorn
    python -m shia_aalim.web         # serve on http://127.0.0.1:8000

FastAPI/uvicorn are optional extras; importing this module (or calling
:func:`create_app`) without them raises a clear install hint rather than a bare
``ImportError``. The corpus is loaded and indexed once at startup with the same
dependency-free TF-IDF embedder as the CLI, so it runs anywhere the CLI does.
"""

