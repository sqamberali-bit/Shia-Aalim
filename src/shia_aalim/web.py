ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_KNOWLEDGE_DIR = ROOT / "data" / "knowledge"
DEFAULT_REGISTRY = ROOT / "data" / "sources" / "registry.yaml"

_FASTAPI_HINT = (
    "The web front-end needs FastAPI and uvicorn, which are optional extras.\n"
    "Install them with:\n\n    pip install -e \".[web]\"\n\n"
    "(or: pip install fastapi uvicorn). The CLI — scripts/demo.py — needs no extras."
)

# Request body models live at *module* level (not inside create_app): with
# ``from __future__ import annotations`` in effect, FastAPI resolves endpoint
# annotations against the function's module globals, so a locally-scoped model
# would silently be misread as a query parameter. Pydantic ships with FastAPI;
# guard the import so merely importing this module never hard-requires the extra.
try:
    from pydantic import BaseModel as _BaseModel

    class AskBody(_BaseModel):
        question: str = ""
        k: Optional[int] = None

    class LectureBody(_BaseModel):
        topic: str = ""
        depth: Optional[int] = None

except ImportError:  # pragma: no cover - only without the web extra
    AskBody = None  # type: ignore
    LectureBody = None  # type: ignore


@dataclass
class AppConfig:
    """How to build the retrieval + generation stack behind the web app."""

    knowledge_dir: Path = DEFAULT_KNOWLEDGE_DIR
    registry_path: Path = DEFAULT_REGISTRY
    embedder: str = "tfidf"
    synthesize: str = "none"
    judge: str = "lexical"
    decompose: str = "none"
    default_k: int = 6


@dataclass
class Stack:
    """The built, ready-to-serve generators plus a little corpus metadata."""

    answers: AnswerGenerator
    lectures: LectureGenerator
    n_documents: int
    config: AppConfig


def build_stack(config: Optional[AppConfig] = None) -> Stack:
    """Load the corpus, build the index, and wire up the generators.

    Pure pipeline code — no web dependency — so it is unit-testable on its own
    and reused by both the API and any embedded use.
    """
    config = config or AppConfig()
    docs = list(iter_knowledge_dir(config.knowledge_dir))
    if not docs:
        raise RuntimeError(
            f"No documents found under {config.knowledge_dir}. Build the corpus "
            "first (python scripts/ingest.py) or point --knowledge-dir at a "
            "directory of .jsonl knowledge files."
        )

    embedder = make_embedder(config.embedder)
    retriever: Retriever = build_index(docs, embedder=embedder)

    synthesizer = make_synthesizer(config.synthesize)
    judge = make_judge(config.judge)
    decomposer = make_decomposer(config.decompose)
    known = _load_known_ids(config.registry_path)

    answers = AnswerGenerator(
        retriever,
        synthesizer=synthesizer,
        known_source_ids=known,
        judge=judge,
        decomposer=decomposer,
    )
    lectures = LectureGenerator(retriever, synthesizer=synthesizer, judge=judge)
    return Stack(answers=answers, lectures=lectures, n_documents=len(docs), config=config)


def _load_known_ids(registry_path: Path) -> Optional[set[str]]:
    try:
        return load_registry_ids(registry_path)
    except FileNotFoundError:
        return None


# ---------------------------------------------------------------------------
# JSON payload builders (structured, so the browser can render badges itself)
# ---------------------------------------------------------------------------


def answer_to_payload(answer: Answer, markdown: str) -> dict:
    return {"answer": answer.to_dict(), "markdown": markdown}


def lecture_to_payload(lecture: Lecture) -> dict:
    return {
        "topic": lecture.topic,
        "generated_on": lecture.generated_on,
        "sections": [
            {
                "title": s.title,
                "body": s.body,
                "synthesized": s.synthesized,
                "note": s.note or "",
                "evidence": [
                    {
                        "text": r.document.text.strip(),
                        "reference": r.document.citation.reference_string(),
                        "confidence": r.document.confidence.value,
                        "evidence_type": r.document.evidence_type.value,
                        "translation": r.document.citation.translation,
                    }
                    for r in s.evidence
                ],
            }
            for s in lecture.sections
        ],
        "markdown": lecture.to_markdown(),
    }


# ---------------------------------------------------------------------------
# FastAPI app
# ---------------------------------------------------------------------------


def create_app(config: Optional[AppConfig] = None, *, stack: Optional[Stack] = None):
    """Build the FastAPI application.

    ``stack`` lets tests inject a pre-built (small-corpus) stack; otherwise it is
    built from ``config`` at creation time. Raises a clear ImportError with an
    install hint if FastAPI isn't available.
    """
    try:
        from fastapi import FastAPI
        from fastapi.responses import HTMLResponse, JSONResponse
    except ImportError as exc:  # pragma: no cover - exercised only without the extra
        raise ImportError(_FASTAPI_HINT) from exc

    stack = stack or build_stack(config)

    app = FastAPI(
        title="Shia-Aalim",
        description="Evidence-first Twelver Shia research & lecture assistant. "
        "No citation = not a fact.",
        version="0.1.0",
    )
    app.state.stack = stack

    @app.get("/", response_class=HTMLResponse)
    async def index() -> str:
        return INDEX_HTML

    @app.get("/api/status")
    async def status() -> dict:
        cfg = stack.config
        return {
            "documents": stack.n_documents,
            "embedder": cfg.embedder,
            "synthesizer": cfg.synthesize,
            "judge": cfg.judge,
            "decomposer": cfg.decompose,
            "default_k": cfg.default_k,
        }

    @app.post("/api/answer")
    async def api_answer(body: AskBody):
        question = (body.question or "").strip()
        if not question:
            return JSONResponse({"error": "question is required"}, status_code=400)
        k = _clamp_int(body.k, default=stack.config.default_k, lo=1, hi=25)
        answer = stack.answers.answer(question, k=k)
        markdown = stack.answers.format_markdown(answer)
        return answer_to_payload(answer, markdown)

    @app.post("/api/lecture")
    async def api_lecture(body: LectureBody):
        topic = (body.topic or "").strip()
        if not topic:
            return JSONResponse({"error": "topic is required"}, status_code=400)
        depth = _clamp_int(body.depth, default=4, lo=1, hi=10)
        lecture = stack.lectures.generate(topic, depth=depth)
        return lecture_to_payload(lecture)

    return app


def _clamp_int(value, *, default: int, lo: int, hi: int) -> int:
    try:
        n = int(value)
    except (TypeError, ValueError):
        return default
    return max(lo, min(hi, n))


