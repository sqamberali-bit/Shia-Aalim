def _narration_payload(doc: Document, *, position: int = -1, chain_length: int = 0) -> dict:
    """A hadith shaped for the rijāl view + drawer: evidence fields + chain + gradings."""
    reading = extract_chain(doc.text)
    return {
        "text": doc.text.strip(),
        "reference": doc.citation.reference_string(),
        "confidence": doc.confidence.value,
        "evidence_type": doc.evidence_type.value,
        "translation": doc.citation.translation,
        "view_status": doc.view_status.value if doc.view_status else None,
        "citation": doc.citation.to_dict(),
        "grade": doc.citation.grade.value,
        "chain": reading.narrators,
        "position": position,
        "chain_length": chain_length or len(reading.narrators),
        "attributions": [
            {"attributor": a.attributor, "grade": a.grade, "work": a.work}
            for a in parse_grade_source(doc.citation.grade_source)
        ],
    }


def _parse_types(values: Optional[list[str]]) -> Optional[list[EvidenceType]]:
    """Turn incoming strings into EvidenceType values; unknown ones are dropped."""
    if not values:
        return None
    out: list[EvidenceType] = []
    for v in values:
        try:
            out.append(EvidenceType(v))
        except ValueError:
            continue
    return out or None


def _parse_sources(values: Optional[list[str]]) -> Optional[set[str]]:
    if not values:
        return None
    picked = {v for v in values if v}
    return picked or None


def _parse_confidence(value: Optional[str]) -> ConfidenceLevel:
    """Map a floor string to a ConfidenceLevel; default LOW (the generator default)."""
    if not value:
        return ConfidenceLevel.LOW
    try:
        return ConfidenceLevel(value)
    except ValueError:
        return ConfidenceLevel.LOW


def _embedder_error(spec: Optional[str], exc: Exception) -> str:
    return (
        f"The '{spec}' embedder is not available in this environment: {exc}. "
        "Semantic models (st:…) need the [embeddings] extra and a reachable "
        "model; switch back to the tfidf index."
    )


def _clamp_int(value, *, default: int, lo: int, hi: int) -> int:
    try:
        n = int(value)
    except (TypeError, ValueError):
        return default
    return max(lo, min(hi, n))


