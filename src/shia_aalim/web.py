def answer_to_payload(answer: Answer, markdown: str) -> dict:
    return {"answer": answer.to_dict(), "markdown": markdown}


def lecture_to_payload(lecture: Lecture) -> dict:
    return {
        "topic": lecture.topic,
        "generated_on": lecture.generated_on,
        "sections": [
            {
                "title": s.title,
                "body": s.body,
                "synthesized": s.synthesized,
                "note": s.note or "",
                "evidence": [
                    {
                        "text": r.document.text.strip(),
                        "reference": r.document.citation.reference_string(),
                        "confidence": r.document.confidence.value,
                        "evidence_type": r.document.evidence_type.value,
                        "translation": r.document.citation.translation,
                        "view_status": r.document.view_status.value if r.document.view_status else None,
                        "citation": r.document.citation.to_dict(),
                    }
                    for r in s.evidence
                ],
            }
            for s in lecture.sections
        ],
        "markdown": lecture.to_markdown(),
    }


def _related_item(item) -> dict:
    """One cross-reference row, shaped like a lecture evidence item for the drawer."""
    doc = item.document
    return {
        "text": doc.text.strip(),
        "reference": doc.citation.reference_string(),
        "confidence": doc.confidence.value,
        "evidence_type": doc.evidence_type.value,
        "translation": doc.citation.translation,
        "view_status": doc.view_status.value if doc.view_status else None,
        "citation": doc.citation.to_dict(),
        "link_type": item.link_type,
        "similarity": round(item.similarity, 4),
    }


def crossref_to_payload(result: CrossRefResult) -> dict:
    v = result.verse
    return {
        "verse": {
            "surah": v.citation.surah,
            "ayah": v.citation.ayah,
            "reference": v.citation.reference_string(),
            "text": v.text.strip(),
            "arabic": v.citation.arabic_text,
            "translation": v.citation.translation,
            "confidence": v.confidence.value,
        },
        "tafsir": [_related_item(i) for i in result.tafsir],
        "hadith": [_related_item(i) for i in result.hadith],
        "verses": [_related_item(i) for i in result.verses],
    }


