def answer_to_payload(answer: Answer, markdown: str) -> dict:
    return {"answer": answer.to_dict(), "markdown": markdown}


def lecture_to_payload(lecture: Lecture) -> dict:
    return {
        "topic": lecture.topic,
        "generated_on": lecture.generated_on,
        "sections": [
            {
                "title": s.title,
                "body": s.body,
                "synthesized": s.synthesized,
                "note": s.note or "",
                "evidence": [
                    {
                        "text": r.document.text.strip(),
                        "reference": r.document.citation.reference_string(),
                        "confidence": r.document.confidence.value,
                        "evidence_type": r.document.evidence_type.value,
                        "translation": r.document.citation.translation,
                        "view_status": r.document.view_status.value if r.document.view_status else None,
                        "citation": r.document.citation.to_dict(),
                    }
                    for r in s.evidence
                ],
            }
            for s in lecture.sections
        ],
        "markdown": lecture.to_markdown(),
    }


